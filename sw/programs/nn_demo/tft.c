void tft_init(int fast)
{
    TFT_CTRL = 2u | (fast ? 8u : 0u);     // reset pin low, backlight on
    delay_ms(10);
    TFT_CTRL = 3u | (fast ? 8u : 0u);     // reset released
    delay_ms(120);
    tft_cmd(0x01);  tft_idle();  delay_ms(150);          // software reset
    tft_cmd(0x11);  tft_idle();  delay_ms(150);          // sleep out
    tft_cmd(0x3A);  tft_data(0x55);                      // 16 bits per pixel
    tft_cmd(0x36);  tft_data(0x08);                      // portrait, BGR (as in the TFT test)
    tft_cmd(0x20);                                       // no colour inversion
    tft_cmd(0x13);                                       // normal mode
    tft_cmd(0x29);                                       // display on (each screen clears itself)
}

void tft_window(int x, int y, int w, int h)
{
    int x1 = x + w - 1, y1 = y + h - 1;
    tft_cmd(0x2A); tft_data(x >> 8); tft_data(x); tft_data(x1 >> 8); tft_data(x1);
    tft_cmd(0x2B); tft_data(y >> 8); tft_data(y); tft_data(y1 >> 8); tft_data(y1);
    tft_cmd(0x2C);
}

void tft_fill(int x, int y, int w, int h, uint16_t colour)
{
    if (w <= 0 || h <= 0) return;
    tft_window(x, y, w, h);
    tft_pix(colour);
    tft_wait();
    TFT_FILL = (uint32_t)(w * h - 1);
}

void tft_image(int x, int y, const int8_t *img, int w, int h, int stride, int scale)
{
    tft_window(x, y, w * scale, h * scale);
    for (int r = 0; r < h; r++) {
        const int8_t *row = img + r * stride;
        for (int rep = 0; rep < scale; rep++) {
            if (scale % 2 == 0) {
                for (int c = 0; c < w; c++) {
                    uint16_t g = tft_grey(row[c]);
                    for (int k = 0; k < scale; k += 2) tft_pix2(g, g);
                }
            } else {
                for (int c = 0; c < w; c++) {
                    uint16_t g = tft_grey(row[c]);
                    for (int k = 0; k < scale; k++) tft_pix(g);
                }
            }
        }
    }
}

void tft_char(int x, int y, char ch, int scale, uint16_t fg, uint16_t bg)
{
    if (ch < 32 || ch > 126) ch = '?';
    const uint8_t *g = &font[(ch - 32) * 12];
    tft_window(x, y, 8 * scale, 12 * scale);
    for (int r = 0; r < 12; r++)
        for (int rep = 0; rep < scale; rep++)
            for (int c = 0; c < 8; c++) {
                uint16_t col = (g[r] >> (7 - c)) & 1 ? fg : bg;
                for (int k = 0; k < scale; k++) tft_pix(col);
            }
}

int tft_text(int x, int y, const char *s, int scale, uint16_t fg, uint16_t bg)
{
    for (; *s; s++, x += 8 * scale) tft_char(x, y, *s, scale, fg, bg);
    return x;
}

int tft_num(int x, int y, uint32_t v, int scale, uint16_t fg, uint16_t bg)
{
    char buf[11];
    int i = 10;
    buf[i] = 0;
    do { buf[--i] = (char)('0' + v % 10); v /= 10; } while (v);
    return tft_text(x, y, &buf[i], scale, fg, bg);
}

int tft_fixed(int x, int y, uint32_t v, int dec, int scale, uint16_t fg, uint16_t bg)
{
    uint32_t p = 1;
    for (int i = 0; i < dec; i++) p *= 10;
    x = tft_num(x, y, v / p, scale, fg, bg);
    if (dec) {
        x = tft_text(x, y, ".", scale, fg, bg);
        uint32_t f = v % p;
        for (uint32_t q = p / 10; q; q /= 10) {
            tft_char(x, y, (char)('0' + f / q % 10), scale, fg, bg);
            x += 8 * scale;
        }
    }
    return x;
}
