# gen_c.py - writes the INT8 network and a few test images as C for the SoC program
# (sw/programs/mnist), plus every test image as a raw file for the PC-side check.
#
#   python3 gen_c.py <output folder for weights.c / weights.h / test_images.c>
#
# Weights are stored as K x F matrices ("transposed"), F padded to a multiple of 4, so 4
# neighbouring filters are one 32-bit word: exactly one B_ROW word of the accelerator.

import sys, numpy as np
from train import load
from quantize import golden, S

N_IMAGES = 4                       # images built into the program (data memory is 16 KB)

def c_array(ctype, name, values, per_line=16):
    vals = [str(int(v)) for v in np.asarray(values).ravel()]
    lines = [', '.join(vals[i:i+per_line]) for i in range(0, len(vals), per_line)]
    return (f'const {ctype} {name}[{len(vals)}] __attribute__((aligned(4))) = {{\n    '
            + ',\n    '.join(lines) + '\n};\n')

def transposed(w, fpad):           # (F, K) -> (K, fpad), zero padding
    F, K = w.shape
    t = np.zeros((K, fpad), np.int64); t[:, :F] = w.T
    return t

if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    q = dict(np.load('weights_int8.npz'))
    xte, yte = load('t10k-images-idx3-ubyte.gz', 't10k-labels-idx1-ubyte.gz')

    head = '// generated by ml/mnist/gen_c.py - do not edit\n'
    with open(f'{out}/weights.c', 'w') as f:
        f.write(head + '#include "weights.h"\n\n')
        f.write(c_array('int8_t',  'w1t', transposed(q['w1'], 8)))      # 9 x 8
        f.write(c_array('int32_t', 'b1',  q['b1']));  f.write(c_array('int32_t', 'm1', q['m1']))
        f.write(c_array('int8_t',  'w2t', transposed(q['w2'], 16)))     # 72 x 16
        f.write(c_array('int32_t', 'b2',  q['b2']));  f.write(c_array('int32_t', 'm2', q['m2']))
        f.write(c_array('int8_t',  'w3t', transposed(q['w3'], 12)))     # 400 x 12 (10 used)
        f.write(c_array('int32_t', 'b3',  q['b3']))
    with open(f'{out}/weights.h', 'w') as f:
        f.write(head + f'''#ifndef WEIGHTS_H
#define WEIGHTS_H
#include <stdint.h>

#define CNN_SHIFT {S}           // requantisation: y = clamp((acc * m + 2^(SHIFT-1)) >> SHIFT, 0, 127)

extern const int8_t  w1t[9 * 8],    w2t[72 * 16],  w3t[400 * 12];
extern const int32_t b1[8],  m1[8], b2[16], m2[16], b3[10];

#endif
''')

    logits, _ = golden(q, xte[:N_IMAGES])
    with open(f'{out}/test_images.c', 'w') as f:
        f.write(head + '#include <stdint.h>\n\n')
        f.write(f'const int n_test_images = {N_IMAGES};\n')
        f.write(c_array('uint8_t', 'test_images', xte[:N_IMAGES], per_line=28))
        f.write(c_array('uint8_t', 'test_labels', yte[:N_IMAGES]))
        f.write('// expected scores from the golden model (ml/mnist/quantize.py)\n')
        f.write(c_array('int32_t', 'test_golden', logits, per_line=10))

    xte.astype(np.uint8).tofile('test_images.raw')          # for host_check
    print('labels of the built-in images:', yte[:N_IMAGES], ' golden predictions:', logits.argmax(1))
