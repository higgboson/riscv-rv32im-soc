# gen_demo.py - writes the race images of the board demo (sw/programs/nn_demo/race_images.c):
# 12 MNIST test images, at least one of each digit, stored with 4 bits per pixel
# (two pixels per byte, first pixel in the low nibble) to save data memory.
#
#   python3 gen_demo.py <output folder>      (run where the MNIST .gz files are)

import sys, numpy as np
from train import load

N = 12
xte, yte = load('t10k-images-idx3-ubyte.gz', 't10k-labels-idx1-ubyte.gz')
pick, seen = [], set()
for i, y in enumerate(yte):                  # first image of each digit, then the next ones
    if y not in seen: pick.append(i); seen.add(y)
    if len(seen) == 10: break
pick += [i for i in range(len(yte)) if i not in pick][:N - len(pick)]

nib = np.minimum((xte[pick].reshape(N, 784).astype(int) + 8) >> 4, 15)
packed = (nib[:, 0::2] | (nib[:, 1::2] << 4)).astype(np.uint8).reshape(-1)

def c_array(ctype, name, values, per_line=24):
    v = [str(int(x)) for x in values]
    body = ',\n'.join('    ' + ', '.join(v[i:i + per_line]) for i in range(0, len(v), per_line))
    return f'const {ctype} {name}[{len(v)}] = {{\n{body}\n}};\n'

with open(f'{sys.argv[1]}/race_images.c', 'w') as f:
    f.write('// generated by ml/mnist/gen_demo.py - do not edit\n#include <stdint.h>\n\n')
    f.write(f'const int n_race_images = {N};\n')
    f.write(c_array('uint8_t', 'race_images', packed))
    f.write(c_array('uint8_t', 'race_labels', yte[pick]))
print('race images: test indices', pick, 'labels', list(yte[pick]))
